"""
Confusion-matrix metrics from one grader's labels.

  python metrics.py claude-opus-5-5     # -> results/metrics-claude-opus-5-5.md

Positives are the vulnerable runs (vulnerable source, successful-attack trace); negatives are the
secure source and the benign trace. The blocked attempt is neither, so it is left out of the
matrix and reported as its own flag rate, as in the attack docs. Two levels are scored:

  flagged    the model said yes (its own Q1 answer)
  diagnosed  on a positive, the grader marked the answer localized; on a negative, a yes is
             still a false positive, so this level only differs from `flagged` in TP/FN
"""

import json
import sys

from judge import ATTACKS, MODELS
from run_study import RESULTS

NAMES = {
    "gpt-oss-120b-turbo": "gpt-oss-120b",
    "deepseek-v3.2": "DeepSeek-V3.2",
    "llama-3.3-70b-instruct-turbo": "Llama-3.3-70B",
    "nvidia-nemotron-3-super-120b-a12b": "Nemotron-3-Super",
    "gemma-4-31b-it": "Gemma-4-31B",
    "deepseek-v3.2-thinking": "DeepSeek-V3.2 (thinking)",
}
ATTACK_NAMES = dict(zip(ATTACKS, ["A1 mint confusion", "A2 sysvar spoof", "A5 missing signer", "A6 arbitrary CPI"]))
TRACKS = {"source": "Source Code", "trace": "Transaction Information"}


def counts(rows, level):
    tp = fn = fp = tn = blocked = 0
    for row in rows:
        said_yes = bool(row["flagged"])
        if row["label"] == "blocked-attempt":
            blocked += said_yes
        elif row["ground_truth_has_bug"]:
            hit = said_yes if level == "flagged" else bool(row["localized"])
            tp += hit
            fn += not hit
        else:
            fp += said_yes
            tn += not said_yes
    return [tp, fn, fp, tn, blocked]


def scores(tp, fn, fp, tn):
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    accuracy = (tp + tn) / (tp + fn + fp + tn)
    return precision, recall, f1, accuracy


def row_line(label, c, show_blocked):
    tp, fn, fp, tn, blocked = c
    precision, recall, f1, accuracy = scores(tp, fn, fp, tn)
    cells = [label, tp, fn, fp, tn, f"{precision:.2f}", f"{recall:.2f}", f"{f1:.2f}", f"{accuracy:.2f}"]
    if show_blocked:
        cells.append(blocked)
    return "| " + " | ".join(str(x) for x in cells) + " |"


def table(title, groups, show_blocked):
    head = ["", "TP", "FN", "FP", "TN", "Precision", "Recall", "F1", "Accuracy"]
    if show_blocked:
        head.append("Blocked flagged")
    lines = [f"#### {title}", "", "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += [row_line(label, c, show_blocked) for label, c in groups]
    return lines + [""]


def add(a, b):
    return [x + y for x, y in zip(a, b)]


def main(judge):
    graded = RESULTS / "graded" / judge
    data = {}
    for attack in ATTACKS:
        for track in TRACKS:
            for model in MODELS:
                data[attack, track, model] = json.loads((graded / f"{attack}-{track}-{model}.json").read_text())

    out = [
        f"# Detection metrics, graded by `{judge}`",
        "",
        "Generated by `detection/metrics.py`. Positives: 100 vulnerable runs per cell. Negatives: 100",
        "secure-source or benign-trace runs per cell. The blocked attempt is excluded from the matrix;",
        "its flag count is shown separately. **Flagged** = the model said yes. **Diagnosed** = the",
        "model also named the planted bug (graded); false positives are the same at both levels.",
        "",
    ]
    for level in ("flagged", "diagnosed"):
        out += [f"## {level.capitalize()}", ""]
        for track, track_name in TRACKS.items():
            out += [f"### {track_name}", ""]
            for attack in ATTACKS:
                groups = [(NAMES[m], counts(data[attack, track, m], level)) for m in MODELS]
                out += table(ATTACK_NAMES[attack], groups, track == "trace")
            pooled = []
            for model in MODELS:
                total = [0] * 5
                for attack in ATTACKS:
                    total = add(total, counts(data[attack, track, model], level))
                pooled.append((NAMES[model], total))
            out += table(f"All four attacks pooled ({track_name})", pooled, track == "trace")

    path = RESULTS / f"metrics-{judge}.md"
    path.write_text("\n".join(out))
    print(f"wrote {path}")


if __name__ == "__main__":
    main(sys.argv[1])
